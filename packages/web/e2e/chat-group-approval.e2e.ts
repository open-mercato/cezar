import { test } from '@e2e-dev/web'
import { expect } from 'e2e'
import { chatFixture } from './chat-fixture'

test('group approval, persisted access and unmentioned reply to the correct task', async ({ app, screen, browser }) => {
 const { base, fixture, receivers, initial, provider, profile } = await chatFixture(app.baseUrl)
 await app.open('/p/default/settings/integrations?integration=' + provider)
 await screen.getByRole('button', 'Enable task control for Existing webhook').tap()
 for (const [label, value] of profile.credentials) await screen.getByLabel(label).fill(value)
 await expect(screen.getByRole('button', 'Continue')).toBeDisabled()
 expect((await fixture()).calls).toBe(0)
 await screen.getByRole('checkbox', 'This bot is dedicated to this project').check()
 await screen.getByRole('button', 'Continue').tap()
 await expect(screen.getByLabel(profile.groupCommand)).toBeVisible()
 const command = await screen.getByLabel(profile.groupCommand).inputValue()
 await fixture('/message', { text: command, group: true })
 await expect(screen.getByRole('checkbox', /all members of this group can read project messages/)).toBeVisible()
 await expect(screen.getByRole('button', 'Activate notifications')).toBeDisabled()
 await screen.getByRole('checkbox', /all members of this group can read project messages/).check()
 const activationResponse = browser.waitForResponse('**/setup/*/activate')
 await screen.getByRole('button', 'Activate notifications').tap()
 const activation = await activationResponse
 expect({ status: activation.status, body: await activation.json() }).toMatchObject({ status: 200 })
 await expect(screen.getByRole('heading', profile.name + ' notifications are active')).toBeVisible()
 await screen.getByRole('checkbox', /Enable optional task control/).check()
 await screen.getByRole('button', 'Continue').tap()
 await expect(screen.getByLabel(profile.privateCommand)).toBeVisible()
 const privateCommand = await screen.getByLabel(profile.privateCommand).inputValue()
 await fixture('/message', { text: privateCommand })
 await expect.poll(async () => { await fixture(); return screen.getByRole('checkbox', /I compared the code sent privately/).count() }).toBe(1)
 await expect(screen.getByRole('button', 'Activate task control')).toBeDisabled()
 await screen.getByRole('checkbox', /I compared the code sent privately/).check()
 await screen.getByRole('button', 'Activate task control').tap()
 await expect(screen.getByText(/task control is enabled/)).toBeVisible()
 await screen.getByRole('button', 'Done').tap()
 const rows = await receivers()
 expect(rows).toHaveLength(1)
 expect(rows[0].id).toBe(initial.seedId)
 expect(rows[0].chatId).toBe(profile.groupChatId)
 expect(rows[0].state).toBe('active')
 await fixture('/restart', {})
 await browser.reload()
 expect((await receivers())[0].chatId).toBe(profile.groupChatId)
 await expect(screen.getByRole('button', 'Enable task control for Existing webhook')).not.toBeVisible()

 await expect.poll(async () => (await fixture()).inbound.bots[0]?.health.state).toBe('polling')
 await fixture('/message', { group: true, text: profile.groupTaskCommand + 'Must not create a group task' })
 await expect.poll(async () => (await fixture()).sent.some((m: any) => /Start new tasks from your private chat/.test(m.text ?? m.content ?? ''))).toBe(true)
 expect(await fetch(base + '/api/v1/runs').then(r => r.json())).toHaveLength(0)
 // An ordinary task launched locally sends its waiting notification to the approved group.
 // Reply through the native thread/reference, with no bot mention or command.
 const created = await fetch(base + '/api/v1/runs', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ workflow: 'quick-task', task: 'Please finish the deterministic fixture group task.', runner: 'claude' }) })
 expect(created.ok).toBe(true)
 const run = await created.json()
 const inGroup = (m: any) => (m.channel ?? m.channel_id) === profile.groupChannel
 await expect.poll(async () => (await fixture()).sent.some((m: any) => inGroup(m) && (m.text ?? m.content ?? '').includes(run.id))).toBe(true)
 await expect.poll(async () => (await fixture()).inbound.bots[0]?.health.state).toBe('polling')
 const groupMessages = (await fixture()).sent.filter(inGroup)
 expect(groupMessages.some((m: any) => (m.text ?? m.content ?? '').includes('(dry-run mock)'))).toBe(false)
 expect((await fixture()).states.flatMap((state: any) => state.correlations).filter((row: any) => row.runId === run.id).every((row: any) => row.privateChat === false)).toBe(true)
 // An unmentioned reply is routed only through a recorded correlation; reply after it exists.
 await expect.poll(async () => (await fixture()).states.flatMap((state: any) => state.correlations).some((row: any) => row.runId === run.id)).toBe(true)
 await fixture('/reply', { runId: run.id, text: 'Please apply the deterministic group fixture reply.' })
 await expect.poll(async () => (await fixture()).events.some((event: any) => event.runId === run.id && event.type === 'user-message' && event.text === '[via ' + profile.name + '] Please apply the deterministic group fixture reply.')).toBe(true)
})
