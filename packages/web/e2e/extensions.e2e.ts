import { test } from '@e2e-dev/web'
import { expect } from 'e2e'

test('installs packed-SDK summary and chat projects, pairs, restarts, disables and uninstalls through the UI', async ({ app, screen, browser }) => {
  const base = app.baseUrl!
  const control = new URL(base); control.port = String(Number(control.port) + 1)
  const fixture = async (path = '/', data?: unknown) => {
    const response = await fetch(new URL(path, control), data === undefined ? {} : { method: 'POST', body: JSON.stringify(data) })
    if (!response.ok) throw Error(await response.text())
    return response.json()
  }
  const initial = await fixture()
  const install = async (path: string, name: string) => {
    await app.open('/settings/global/extensions')
    await screen.getByLabel('Extension folder or package').fill(path)
    await screen.getByRole('button', 'Preview install').tap()
    await expect(screen.getByRole('dialog', `Install ${name}?`)).toBeVisible()
    await screen.getByRole('button', 'Approve and install').tap()
    const row = screen.getByRole('listitem', name)
    await row.getByRole('button', 'Enable', { exact: true }).tap()
    await screen.getByRole('button', 'Approve and enable').tap()
    await expect(row.getByRole('button', 'Disable', { exact: true })).toBeVisible()
  }
  await install(initial.summary, 'Project summary')
  await screen.getByRole('region', 'Project summary').getByRole('button', 'Refresh summary', { exact: true }).tap()
  // One crash is absorbed: the host restarts the worker (RestartBudget) and the panel answers again.
  await fixture('/crash-summary', {})
  const summaryRow = screen.getByRole('listitem', 'Project summary')
  // The fixture returns once the host reports `running` again; the UI proves it by answering a command.
  await expect(summaryRow.getByRole('button', 'Review and retry', { exact: true })).not.toBeVisible()
  await screen.getByRole('region', 'Project summary').getByRole('button', 'Refresh summary', { exact: true }).tap()
  await expect(summaryRow.getByText('Summary refreshed', { exact: true })).toBeVisible()
  // A crash loop exhausts the budget: the row fails and offers Review and retry.
  await fixture('/exhaust-summary', {})
  await summaryRow.getByRole('button', 'Review and retry', { exact: true }).tap()
  await screen.getByRole('button', 'Approve and enable').tap()
  await expect(summaryRow.getByRole('button', 'Review and retry', { exact: true })).not.toBeVisible()
  await fixture('/update-summary', {})
  await summaryRow.getByRole('button', 'Reload').tap()
  await expect(screen.getByText('Added permissions: task.create', { exact: true })).toBeVisible()
  await screen.getByRole('button', 'Cancel install').tap()
  await screen.getByRole('region', 'Project summary').getByRole('button', 'Refresh summary', { exact: true }).tap()
  // Placements (spec 2026-11-07-extension-placements): the same install flow, then the
  // three cockpit surfaces — palette group, sidebar section, task view — all without a restart.
  await install(initial.placements, 'Placements fixture')
  await app.open('/p/default/')
  await browser.keyboard.press('Control+k')
  await screen.getByRole('option', 'Placements fixture: Say hello').tap()
  await expect(screen.getByText('Hello from the placements fixture', { exact: true })).toBeVisible()
  await screen.getByRole('button', 'Dismiss', { exact: true }).tap()
  const sidebarSection = screen.getByRole('region', 'Fixture sidebar')
  await sidebarSection.getByRole('button', 'Fixture sidebar', { exact: true }).tap()
  await expect(screen.getByText('Sidebar panel body from the fixture', { exact: true })).toBeVisible()
  await sidebarSection.getByRole('button', 'Say hello from the sidebar', { exact: true }).tap()
  await expect(sidebarSection.getByText('Hello from the placements fixture', { exact: true })).toBeVisible()
  await browser.reload()
  await expect(screen.getByText('Sidebar panel body from the fixture', { exact: true })).toBeVisible()
  const createdResponse = await fetch(new URL('/api/v1/runs', base), { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ workflow: 'quick-task', task: 'Placements fixture task', runner: 'claude' }) })
  const createdBody = await createdResponse.text()
  if (!createdResponse.ok) throw Error(`POST /api/v1/runs answered ${createdResponse.status}: ${createdBody.slice(0, 300)}`)
  const created = JSON.parse(createdBody) as { id: string }
  await app.open(`/p/default/tasks/${created.id}/extensions`)
  const taskCard = screen.getByRole('region', 'Fixture task notes')
  await expect(taskCard.getByText(/Placements fixture task/)).toBeVisible()
  await screen.getByRole('button', 'Summarize this task', { exact: true }).tap()
  await expect(screen.getByText(`Summarized task ${created.id}`, { exact: true })).toBeVisible()
  await app.open('/settings/global/extensions')
  const placementsRow = screen.getByRole('listitem', 'Placements fixture')
  await placementsRow.getByRole('button', 'Disable', { exact: true }).tap()
  await expect(placementsRow.getByRole('button', 'Enable', { exact: true })).toBeVisible()
  await app.open('/p/default/')
  await expect(screen.getByRole('region', 'Fixture sidebar')).not.toBeVisible()
  await app.open('/settings/global/extensions')
  await screen.getByRole('listitem', 'Placements fixture').getByRole('button', 'Uninstall', { exact: true }).tap()
  await screen.getByRole('button', 'Uninstall and keep data').tap()
  // Uninstall and keep data retains the record as Missing for a reinstall (spec 2026-11-05-extension-system-design, Installation, data, lifecycle).
  await expect(screen.getByRole('listitem', 'Placements fixture').getByText('Missing', { exact: true })).toBeVisible()
  await expect(screen.getByRole('listitem', 'Placements fixture').getByText(/keeps its approval/)).toBeVisible()
  await expect(screen.getByRole('listitem', 'Placements fixture').getByRole('button', 'Uninstall', { exact: true })).not.toBeVisible()
  await install(initial.chat, 'Mattermost')
  await app.open('/p/default/settings/integrations?integration=open-mercato.mattermost%2Fchat')
  await screen.getByRole('button', 'Connect Mattermost', { exact: true }).tap()
  await screen.getByRole('button', /Notifications and task control/).tap()
  await screen.getByLabel('Mattermost HTTPS server URL').fill('https://mattermost.example')
  await screen.getByLabel('Dedicated bot access token').fill('fixture-token')
  await screen.getByRole('checkbox', 'This bot is dedicated to this project').check()
  await screen.getByRole('button', 'Continue', { exact: true }).tap()
  await expect(screen.getByLabel('Setup command')).toBeVisible()
  const command = await screen.getByLabel('Setup command').inputValue()
  await fixture('/message', { text: command })
  await expect(screen.getByRole('checkbox', 'Enable task control for this private chat')).toBeVisible()
  await screen.getByRole('checkbox', 'Enable task control for this private chat').check()
  await screen.getByRole('button', 'Activate notifications and task control').tap()
  await expect(screen.getByText(/task control is enabled/)).toBeVisible()
  await screen.getByRole('button', 'Done', { exact: true }).tap()
  expect((await fixture()).inbound.grants).toHaveLength(1)
  expect((await fixture()).sent.some((message: { message: string }) => message.message.includes('Test message'))).toBe(true)
  await fixture('/restart', {})
  await browser.reload()
  await expect.poll(async () => (await fixture()).inbound?.grants.length).toBe(1)
  await app.open('/settings/global/extensions')
  const chat = screen.getByRole('listitem', 'Mattermost')
  await chat.getByRole('button', 'Disable', { exact: true }).tap()
  await expect(chat.getByRole('button', 'Enable', { exact: true })).toBeVisible()
  expect((await fixture()).inbound).toBeUndefined()
  await screen.getByRole('region', 'Project summary').getByRole('button', 'Refresh summary', { exact: true }).tap()
  await chat.getByRole('button', 'Uninstall', { exact: true }).tap()
  // The paired bot's receiver still names the extension, so deleting data would keep its row.
  await expect(screen.getByText(/a webhook receiver still uses it/)).toBeVisible()
  await screen.getByRole('button', 'Uninstall and keep data').tap()
  // Uninstall and keep data retains the record as Missing for a reinstall (spec 2026-11-05-extension-system-design, Installation, data, lifecycle).
  await expect(chat.getByText('Missing', { exact: true })).toBeVisible()
  await expect(chat.getByRole('button', 'Uninstall', { exact: true })).not.toBeVisible()
  const summary = screen.getByRole('listitem', 'Project summary')
  await summary.getByRole('button', 'Disable', { exact: true }).tap()
  await expect(summary.getByRole('button', 'Enable', { exact: true })).toBeVisible()
  await summary.getByRole('button', 'Uninstall', { exact: true }).tap()
  await screen.getByRole('checkbox', /Delete this extension’s data and secrets/).check()
  await screen.getByRole('button', 'Uninstall and delete data').tap()
  // Deleting data also drops the approval, so no Missing row is left behind (spec 2026-11-05-extension-system-design, Installation, data, lifecycle).
  await expect(screen.getByRole('listitem', 'Project summary')).not.toBeVisible()
  // Only the task the spec started itself exists: no extension proposal became a run on its own.
  expect((await fixture()).runs.map((run: { id: string }) => run.id)).toEqual([created.id])
})
