import { test } from '@e2e-dev/web'
import { expect } from 'e2e'
import { chatFixture } from './chat-fixture'

test('manual private webhook upgrade, consent, confirmed task and persisted access', async ({ app, screen, browser }) => {
 const { base, fixture, receivers, initial, provider, profile } = await chatFixture(app.baseUrl)
 await app.open('/p/default/settings/integrations?integration=' + provider)
 if (profile.upgradeThroughChooser) {
  await screen.getByRole('button', 'Connect ' + profile.name).tap()
  await screen.getByRole('button', /^Notifications and task control/).tap()
 }
 await screen.getByRole('button', 'Enable task control for Existing webhook').tap()
 for (const [label, value] of profile.credentials) await screen.getByLabel(label).fill(value)
 await expect(screen.getByRole('button', 'Continue')).toBeDisabled()
 expect((await fixture()).calls).toBe(0)
 await screen.getByRole('checkbox', 'This bot is dedicated to this project').check()
 await screen.getByRole('button', 'Continue').tap()
 await expect(screen.getByLabel(profile.privateCommand)).toBeVisible()
 await expect(screen.getByRole('button', 'Activate notifications')).toBeDisabled()
 const command = await screen.getByLabel(profile.privateCommand).inputValue()
 await fixture('/message', { text: command })
 await expect(screen.getByRole('checkbox', 'Enable task control for this private chat')).toBeVisible()
 await screen.getByRole('checkbox', 'Enable task control for this private chat').check()
 await screen.getByRole('checkbox', 'Start tasks').check()
 await screen.getByRole('button', 'Activate notifications and task control').tap()
 await expect(screen.getByText(/task control is enabled/)).toBeVisible()
 await screen.getByRole('button', 'Done').tap()
 const rows = await receivers()
 expect(rows).toHaveLength(1)
 expect(rows[0].id).toBe(initial.seedId)
 expect(rows[0].state).toBe('active')
 expect(rows[0].chatId).toBe(profile.privateChatId)
 expect((await fixture()).sent.some((m: any) => /Test message/.test(m.text ?? m.content))).toBe(true)
 await fixture('/restart', {})
 await browser.reload()
 await expect(screen.getByRole('button', 'Enable task control for Existing webhook')).not.toBeVisible()
 await expect.poll(async () => (await fixture()).inbound.bots[0]?.health.state).toBe('polling')
 expect((await receivers())[0].chatId).toBe(profile.privateChatId)
 await fixture('/message', { text: profile.taskCommand + 'Please finish the deterministic fixture task.' })
 await expect.poll(async () => (await fixture()).sent.some((m: any) => (m.text ?? m.content ?? '').startsWith('Start a new task?'))).toBe(true)
 expect(await fetch(base + '/api/v1/runs').then(r => r.json())).toHaveLength(0)
 await fixture('/confirm', {})
 await expect.poll(async () => (await fetch(base + '/api/v1/runs').then(r => r.json())).length).toBe(1)
 await expect.poll(async () => (await fetch(base + '/api/v1/runs').then(r => r.json()))[0]?.status).toBe('waiting')
 await fixture('/finish', {})
 await expect.poll(async () => (await fixture()).sent.some((m: any) => profile.completed.test(m.text ?? m.content ?? ''))).toBe(true)
 const runs = await fetch(base + '/api/v1/runs').then(r => r.json())
 expect(runs).toHaveLength(1)
 const run = await fetch(base + '/api/v1/runs/' + runs[0].id).then(r => r.json())
 expect(run.chatSource?.id).toEqual(expect.any(String))
 for (const key of ['chatId', 'userId', 'botId', 'state']) expect(run.chatSource?.[key]).toBeUndefined()
})
